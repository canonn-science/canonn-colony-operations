const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const dest = path.resolve(repoRoot, 'src/app/data/canonn-members-generated.ts');

// Published from the Canonn/CDSR squadron membership Google Sheet.
const SHEET_URL =
  'https://docs.google.com/spreadsheets/d/e/2PACX-1vS5TMBu2KJQBaNqSBropWVdXUcOjz-wJe57e8h4pRPzr7zZ066yjO-H2Z7hqZe-fOVSpzy-7dzAqU2z/pub?gid=1407641049&single=true&output=tsv';

/** Parses the sheet's `Name\tRank\tLast Activity\tSquadron` TSV into `{ name, squadron }` rows. */
function parseMembers(tsv) {
  const lines = tsv.split(/\r?\n/);
  const members = [];
  // Row 0 is the header.
  for (const line of lines.slice(1)) {
    if (!line.trim()) {
      continue;
    }
    const [name, , , squadron] = line.split('\t');
    if (name && name.trim() && squadron && squadron.trim()) {
      members.push({ name: name.trim(), squadron: squadron.trim() });
    }
  }
  return members;
}

async function main() {
  let members;
  try {
    const response = await fetch(SHEET_URL);
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }
    members = parseMembers(await response.text());
  } catch (error) {
    if (fs.existsSync(dest)) {
      console.warn(`Couldn't refresh the Canonn member roster (${error.message}); keeping the checked-in version.`);
      return;
    }
    throw error;
  }

  const output = `// AUTO-GENERATED by scripts/fetch-canonn-members.js at build time.
// Do not edit by hand; run \`npm run fetch-canonn-members\` (also runs on prestart/prebuild).
import { CanonnMember } from './canonn-members';

export const CANONN_MEMBERS: readonly CanonnMember[] = ${JSON.stringify(members, null, 2)};
`;

  fs.writeFileSync(dest, output);
  console.log(`Wrote ${members.length} Canonn/CDSR members to ${path.relative(repoRoot, dest)}`);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
