const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const membersDest = path.resolve(repoRoot, 'src/app/data/canonn-members-generated.ts');
const preferencesDest = path.resolve(repoRoot, 'src/app/data/faction-preferences-generated.ts');

// Both published from the Canonn/CDSR squadron membership Google Sheet (different tabs).
const SHEET_BASE =
  'https://docs.google.com/spreadsheets/d/e/2PACX-1vS5TMBu2KJQBaNqSBropWVdXUcOjz-wJe57e8h4pRPzr7zZ066yjO-H2Z7hqZe-fOVSpzy-7dzAqU2z/pub';
const MEMBERS_URL = `${SHEET_BASE}?gid=1407641049&single=true&output=tsv`;
const PREFERENCES_URL = `${SHEET_BASE}?gid=36972429&single=true&output=tsv`;

/** Parses the sheet's `Name\tRank\tLast Activity\tSquadron` TSV into `{ name, squadron }` rows. */
function parseMembers(tsv) {
  const lines = tsv.split(/\r?\n/);
  const members = [];
  // Row 0 is the header.
  for (const line of lines.slice(1)) {
    if (!line.trim()) {
      continue;
    }
    const [name, , , squadron] = line.split('\t');
    if (name && name.trim() && squadron && squadron.trim()) {
      members.push({ name: name.trim(), squadron: squadron.trim() });
    }
  }
  return members;
}

/**
 * Parses the `Timestamp\tFaction Name\tcmdr\tAlt Faction` TSV into one `{ cmdr, factions }` row
 * per commander (case-insensitive), merging the factions of repeated submissions.
 */
function parseFactionPreferences(tsv) {
  const byCmdr = new Map();
  for (const line of tsv.split(/\r?\n/).slice(1)) {
    if (!line.trim()) {
      continue;
    }
    const [, factionName, cmdr, altFaction] = line.split('\t');
    if (!cmdr || !cmdr.trim()) {
      continue;
    }
    const key = cmdr.trim().toLowerCase();
    const entry = byCmdr.get(key) ?? { cmdr: cmdr.trim(), factions: [] };
    for (const faction of [factionName, altFaction]) {
      const name = faction && faction.trim();
      if (name && !entry.factions.includes(name)) {
        entry.factions.push(name);
      }
    }
    byCmdr.set(key, entry);
  }
  return [...byCmdr.values()].filter(entry => entry.factions.length > 0);
}

/** Fetches `url` and writes `render(parsed)` to `dest`; keeps the checked-in file if the fetch fails. */
async function refresh({ label, url, dest, parse, render }) {
  let rows;
  try {
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }
    rows = parse(await response.text());
  } catch (error) {
    if (fs.existsSync(dest)) {
      console.warn(`Couldn't refresh the ${label} (${error.message}); keeping the checked-in version.`);
      return;
    }
    throw error;
  }
  fs.writeFileSync(dest, render(rows));
  console.log(`Wrote ${rows.length} ${label} rows to ${path.relative(repoRoot, dest)}`);
}

async function main() {
  await refresh({
    label: 'Canonn/CDSR member roster',
    url: MEMBERS_URL,
    dest: membersDest,
    parse: parseMembers,
    render: members => `// AUTO-GENERATED by scripts/fetch-canonn-members.js at build time.
// Do not edit by hand; run \`npm run fetch-canonn-members\` (also runs on prestart/prebuild).
import { CanonnMember } from './canonn-members';

export const CANONN_MEMBERS: readonly CanonnMember[] = ${JSON.stringify(members, null, 2)};
`,
  });
  await refresh({
    label: 'commander faction preferences',
    url: PREFERENCES_URL,
    dest: preferencesDest,
    parse: parseFactionPreferences,
    render: preferences => `// AUTO-GENERATED by scripts/fetch-canonn-members.js at build time.
// Do not edit by hand; run \`npm run fetch-canonn-members\` (also runs on prestart/prebuild).
import { FactionPreference } from './faction-preferences';

export const FACTION_PREFERENCES: readonly FactionPreference[] = ${JSON.stringify(preferences, null, 2)};
`,
  });
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
