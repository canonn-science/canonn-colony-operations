const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const repoRoot = path.resolve(__dirname, '..');
const dest = path.resolve(repoRoot, 'src/app/build-info.ts');

/**
 * Identifies the current build so a persisted (localStorage) cache can be tied to it —
 * see BUILD_ID's usage in canonn-bgs.service.ts. The short git SHA is stable across a
 * deploy and changes on every new commit; falls back to a timestamp if git isn't available.
 */
function resolveBuildId() {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: repoRoot }).toString().trim();
  } catch {
    return `dev-${Date.now()}`;
  }
}

const buildId = resolveBuildId();

const output = `// AUTO-GENERATED by scripts/generate-build-info.js at build time.
// Do not edit by hand; run \`npm run generate-build-info\` (also runs on prestart/prebuild).
export const BUILD_ID = ${JSON.stringify(buildId)};
`;

fs.writeFileSync(dest, output);
console.log(`Wrote build id "${buildId}" to ${path.relative(repoRoot, dest)}`);
